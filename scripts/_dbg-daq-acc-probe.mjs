import puppeteer from 'puppeteer-core'
const ROOT = 'http://127.0.0.1:3000'
const sleep = ms => new Promise(r => setTimeout(r, ms))
const login = await fetch(`${ROOT}/api/users/login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'zhangwei@awshop.io', password: 'Awshop@123' }) }).then(r => r.json())
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--no-sandbox', '--disable-gpu', '--window-size=1600,1000'] })
const page = await browser.newPage()
const errors = []
page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 140)) })
page.on('pageerror', e => errors.push(`PAGEERROR: ${String(e).slice(0, 140)}`))
await page.setViewport({ width: 1600, height: 1000, deviceScaleFactor: 1.25 })
await page.setCookie({ name: 'token', value: login.data.token, domain: '127.0.0.1', path: '/' })
await page.goto(`${ROOT}/daq`, { waitUntil: 'domcontentloaded', timeout: 45000 })
await sleep(7000)
console.log('v-if 还是 class 切换? body 在收起态是否存在于 DOM:', await page.evaluate(() => !!document.querySelector('.opt-body')))
await page.click('.opt-head')
await sleep(600)
console.log('chevron.open:', await page.evaluate(() => document.querySelector('.opt-chevron')?.classList.contains('open')))
console.log('body.open:', await page.evaluate(() => document.querySelector('.opt-body')?.classList.contains('open')))
console.log('body 高度:', await page.evaluate(() => document.querySelector('.opt-body')?.getBoundingClientRect().height))
console.log('body maxHeight computed:', await page.evaluate(() => getComputedStyle(document.querySelector('.opt-body')).maxHeight))
console.log('body 可见内容行数:', await page.evaluate(() => document.querySelectorAll('.opt-list .opt-row').length))
console.log('errors:', errors.length ? errors.slice(0, 3) : 'none')
await browser.close()
console.log('DONE')
