def sha256(path: Path | str) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_mission():
    for name, expected in SOURCES.items():
        if sha256(ROOT / name) != expected:
            raise ValueError(f"Frozen B source hash mismatch: {name}")
    run = json.loads((ROOT / next(iter(SOURCES))).read_text(encoding="utf-8-sig"))
    env = run["env"]
    if not (env["runId"] == ARCHIVE and env["profile"] == "integrated"
            and env["verdict"]["ok"]):
        raise ValueError("Expected the governing integrated B archive")
    mission = env["biax"]["missionTraj"]
    if [row["iter"] for row in mission] != list(range(5)):
        raise ValueError("Expected baseline and four archived intervention indices")
    log = (ROOT / f"bench/results/{ARCHIVE}/agentteam-biax.log").read_text(encoding="utf-8-sig")
    if log.count("judge=keep") != 4 or "terminal=COMPLETED" not in log:
        raise ValueError("Mission outcome annotations no longer match the trace")
    return env, mission


