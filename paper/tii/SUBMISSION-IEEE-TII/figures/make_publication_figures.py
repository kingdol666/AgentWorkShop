def check_pdf(name):
    """Inspect an existing PDF without writing to any owner's outputs."""
    relative, size = FIGURES[name]
    with fitz.open(OUT / relative) as doc:
        if len(doc) != 1:
            raise ValueError(f"Expected single-page figure: {name}")
        page = doc[0]
        spans = [s for b in page.get_text("dict")["blocks"] if "lines" in b
                 for line in b["lines"] for s in line["spans"] if s["text"].strip()]
        fonts = page.get_fonts(full=True)
        # Font extents can exceed actual ink (including multiline headings).
        # Record metric intersections for review, not as proof of visual overlap.
        overlaps = []
        for i, first in enumerate(spans):
            for second in spans[i + 1:]:
                intersection = fitz.Rect(first["bbox"]) & fitz.Rect(second["bbox"])
                if intersection.width > 0.75 and intersection.height > 0.75:
                    overlaps.append([first["text"], second["text"]])
        # The preserved Chromium architecture PDF has a 0.03 pt metric overhang.
        bounds = page.rect + (-0.05, -0.05, 0.05, 0.05)
        outside = [s["text"] for s in spans if not bounds.contains(fitz.Rect(s["bbox"]))]
        minimum = min((s["size"] for s in spans), default=0)
        info = {
            "size_in": [round(page.rect.width / 72, 4), round(page.rect.height / 72, 4)],
            "raster_images_in_pdf": len(page.get_image_info()),
            "embedded_fonts": bool(fonts) and all(bool(doc.extract_font(f[0])[3]) for f in fonts),
            "fonts": sorted({f[3] for f in fonts}),
            "minimum_font_pt": round(minimum, 4),
            "minimum_annotation_font_pt": round(minimum, 4),
            "text_spans": len(spans), "spans_outside_canvas": outside,
            "font_metric_overlap_pairs": overlaps,
            "font_metric_note": "Metric boxes are not glyph-ink bounds; visual review is separate.",
            "canvas_tolerance_pt": 0.05,
            "author_metadata": doc.metadata.get("author", ""),
            "raster_policy": ("Authentic screenshot crops; 8 pt minimum applies to vector annotations, not source UI pixels."
                              if name == "fig-operational-walkthrough" else "Vector only."),
        }
        if (info["size_in"] != list(size)
                or (info["raster_images_in_pdf"] and name != "fig-operational-walkthrough")
                or not info["embedded_fonts"] or minimum < 8 - 1e-4
                or outside or info["author_metadata"]):
            raise ValueError(f"Figure QA failed for {name}: {info}")
        return info


def save_and_check(fig, name):
    pdf, proof = figure_paths(name)
    pdf.parent.mkdir(parents=True, exist_ok=True)
    try:
        fig.savefig(pdf, metadata={"Creator": "Matplotlib publication figure generator",
                                   "Author": None, "CreationDate": None, "ModDate": None},
                    facecolor="white")
    finally:
        plt.close(fig)
    info = check_pdf(name)
    if info["font_metric_overlap_pairs"]:
        raise ValueError(f"Mission text overlaps: {info['font_metric_overlap_pairs']}")
    with fitz.open(pdf) as doc:
        doc[0].get_pixmap(dpi=300, alpha=False).save(proof)
    info["proof_dpi"] = 300
    return info


def _xml_cells(source: Path):
    cells = list(ET.parse(source).getroot().iter("mxCell"))
    ids = [cell.get("id") for cell in cells]
    if not cells or len(ids) != len(set(ids)):
        raise ValueError("Figure 3 requires native XML cells with unique ids")
    vertices = {cell.get("id") for cell in cells if cell.get("vertex") == "1"}
    edges = [cell for cell in cells if cell.get("edge") == "1"]
    icon_slots = [cell for cell in cells if cell.get("iconPlaceholder") == "true"]
    invalid_edges = [cell.get("id") for cell in edges
                     if cell.get("source") not in vertices or cell.get("target") not in vertices]
    cards = {cell.get("id") for cell in cells if cell.get("role") == "card"}
    if not cards or {slot.get("id") for slot in icon_slots} != {f"{card}-icon-slot" for card in cards}:
        raise ValueError("Figure 3 requires one named blank icon slot per card")
    for slot in icon_slots:
        geometry = slot.find("mxGeometry")
        if (slot.get("parent") not in ids or slot.get("value", "").strip() or geometry is None
                or float(geometry.get("width", "0")) <= 0 or float(geometry.get("height", "0")) <= 0):
            raise ValueError(f"Invalid blank icon slot: {slot.get('id')}")
    return cells, edges, icon_slots, invalid_edges


def verify_fig3_provenance():
    """Match current XML and every export to the renderer's hash receipt.

    This checks the owner's recorded provenance and PDF text against XML; it
    does not claim an independent geometry rerender without an exporter.
    """
    source, output = ROOT / FIG3_SOURCE, ROOT / FIG3_OUTPUT
    if not source.is_file() or not output.is_file() or not FIG3_QA.is_file():
        raise ValueError("Figure 3 XML, PDF, and QA provenance files are required; use --export-fig3")
    cells, edges, icon_slots, invalid_edges = _xml_cells(source)
    if invalid_edges:
        raise ValueError(f"Figure 3 has unresolved source/target ids: {invalid_edges}")
    qa = json.loads(FIG3_QA.read_text(encoding="utf-8"))
    # Owner receipts may contain Windows absolute paths even on another host.
    records = {PureWindowsPath(record["submission"]).name: record["sha256"]
               for record in qa.get("files", [])}
    for path in [source, output, output.with_suffix(".svg"), output.with_suffix(".png")]:
        if not path.is_file() or records.get(path.name) != sha256(path):
            raise ValueError(f"Figure 3 renderer provenance hash mismatch: {path.name}; use --export-fig3")
    expected = {"native_drawio_cells": len(cells), "native_connectors": len(edges), "icon_slots": len(icon_slots)}
    if (qa.get("xml_native_cells", qa.get("native_drawio_cells")) != len(cells)
            or qa.get("native_connectors") != len(edges)
            or ("icon_slots" in qa and qa["icon_slots"] != len(icon_slots))):
        raise ValueError(f"Figure 3 XML/PDF cell counts drifted: expected {expected}")
    info = check_pdf("fig3-governed-supervisory-workflow")
    with fitz.open(output) as doc:
        text = " ".join(doc[0].get_text().split())
    missing = [cell.get("id") for cell in cells
               if " ".join(cell.get("value", "").split()) not in text]
    if missing:
        raise ValueError(f"Figure 3 PDF is missing current XML labels: {missing}")
    if (qa.get("pdf_raster_images") != info["raster_images_in_pdf"]
            or qa.get("layout_issues", qa.get("measured_layout_issues"))
            or qa.get("minimum_pdf_font_pt", 0) < 8):
        raise ValueError("Figure 3 renderer QA does not satisfy vector/font requirements")
    return {"source_sha256": sha256(source), "output_sha256": sha256(output), **expected,
            "minimum_pdf_font_pt": info["minimum_font_pt"],
            "verification": "Owner export receipt hashes and current XML/PDF labels; no independent geometry rerender.",
            "exporter_status": "External XML-derived pipeline; no checked-in export script."}


def verify_fig1_provenance():
    qa = json.loads(FIG1_QA.read_text(encoding="utf-8"))
    if qa.get("generator_sha256") != sha256(FIG1_GENERATOR):
        raise ValueError("Figure 1 generator hash mismatch; rerun publication/make_fig1.py")
    suffixes = {"pdf": ".pdf", "svg": ".svg", "png": ".png", "grayscale_png": "-grayscale.png"}
    for kind, suffix in suffixes.items():
        path = OUT / f"publication/fig1-supervisory-binding{suffix}"
        if qa.get("sha256", {}).get(kind) != sha256(path):
            raise ValueError(f"Figure 1 output hash mismatch: {path.name}")
    if qa.get("preserved_reference_sha256") != sha256(OUT / "gpt/fig1-intro-tii.png"):
        raise ValueError("Figure 1 preserved reference hash mismatch")
    return {"generator_sha256": qa["generator_sha256"], "sha256": qa["sha256"],
            "context_snapshot_note": "Owner QA input_assets are historical editorial context, not current benchmark inputs."}


def verify_walkthrough_provenance():
    qa = json.loads(WALKTHROUGH_PROVENANCE.read_text(encoding="utf-8"))
    folder = OUT / "walkthrough"
    source = folder / "aw_working-source.png"
    if qa.get("source") != source.name or qa.get("source_sha256") != sha256(source):
        raise ValueError("Walkthrough original screenshot hash mismatch")
    if qa.get("output_pdf_sha256") != sha256(folder / "fig-operational-walkthrough.pdf"):
        raise ValueError("Walkthrough output PDF hash mismatch")
    with Image.open(source) as original:
        original = original.convert("RGB")
        if list(original.size) != qa.get("original_size") or len(qa.get("panels", [])) != 4:
            raise ValueError("Walkthrough screenshot dimensions/panels do not match provenance")
        for index, panel in enumerate(qa["panels"], 1):
            crop = folder / f"ui-crop-{index}.png"
            if (panel.get("panel") != index or panel.get("source_ui_pixels_modified") is not False
                    or panel.get("crop_sha256") != sha256(crop)):
                raise ValueError(f"Walkthrough crop hash/provenance mismatch: {crop.name}")
            with Image.open(crop) as actual:
                expected = original.crop(panel["crop_xyxy"])
                if actual.size != expected.size or actual.convert("RGB").tobytes() != expected.tobytes():
                    raise ValueError(f"Walkthrough crop pixels differ from original: {crop.name}")
    return {"source_sha256": qa["source_sha256"], "output_pdf_sha256": qa["output_pdf_sha256"],
            "original_crop_pixels_verified": True,
            "scope": "The supplied screenshot itself is the original crop source; no upstream screenshot is required."}


