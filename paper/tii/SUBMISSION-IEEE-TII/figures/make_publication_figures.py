def verify_metadata():
    manifest = json.loads((OUT / "source-manifest.json").read_text(encoding="utf-8"))
    expected_outputs = {relative for name, (pdf, _) in FIGURES.items() for relative in [pdf, *EXTRA_OUTPUTS[name]]}
    if (manifest.get("schema_version") != 2 or set(manifest.get("figures", {})) != set(FIGURES)
            or set(manifest.get("outputs", {})) != expected_outputs):
        raise ValueError("Aggregate metadata does not describe the current five figures; use --refresh-metadata")
    for field, base in (("outputs", OUT), ("source_hashes", ROOT), ("generator_hashes", OUT), ("provenance_hashes", OUT)):
        for name, digest in manifest[field].items():
            if sha256(base / name) != digest:
                raise ValueError(f"Metadata hash mismatch in {field}: {name}; use --refresh-metadata after owner completion")
    for filename, field in (("plotted-data.json", "plotted_data_sha256"), ("figure-qa.json", "figure_qa_sha256")):
        if sha256(OUT / filename) != manifest[field]:
            raise ValueError(f"Metadata hash mismatch: {filename}")
    qa = json.loads((OUT / "figure-qa.json").read_text(encoding="utf-8"))
    for name, digest in qa["protected_asset_hashes"].items():
        if sha256(OUT / name) != digest:
            raise ValueError(f"Protected asset hash mismatch: {name}")
    _, mission = load_mission()
    if json.loads((OUT / "plotted-data.json").read_text(encoding="utf-8"))["mission"] != mission:
        raise ValueError("Plotted mission data differs from frozen B")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--skip-fig1", action="store_true", help="preserve Figure 1; regenerate only the mission")
    parser.add_argument("--verify-only", action="store_true", help="read-only verification of all five assets and stored metadata")
    parser.add_argument("--refresh-metadata", action="store_true", help="validate all five existing assets and refresh ONLY aggregate JSON metadata; no figure generators")
    parser.add_argument("--export-fig3", action="store_true", help="print explicit owner/export/receipt instructions; do not render or write")
    args = parser.parse_args(argv)
    if args.export_fig3:
        print_fig3_export_instructions()
        return 0

    regenerate = not (args.verify_only or args.refresh_metadata)
    allowed = (set() if not regenerate else MISSION_OUTPUTS | (set() if args.skip_fig1 else FIG1_OUTPUTS))
    before_inputs = input_hashes()
    before_assets = _protected_binary_hashes(allowed)
    before_receipts = {path: sha256(path) for path in (FIG3_QA, WALKTHROUGH_PROVENANCE)}
    if not regenerate or args.skip_fig1:
        before_receipts[FIG1_QA] = sha256(FIG1_QA)
    try:
        # Preflight read-only sources and externally owned exports before any generator writes.
        env, mission = load_mission()
        verify_preserved_assets()
        provenance = {"fig3-governed-supervisory-workflow": verify_fig3_provenance(),
                      "fig-operational-walkthrough": verify_walkthrough_provenance()}
        if regenerate:
            configure()
            if not args.skip_fig1:
                _run_fig1_generator()
            save_and_check(mission_figure(mission), "fig-agentteam-mission")
        provenance["fig1-supervisory-binding"] = verify_fig1_provenance()
        qa = {name: check_pdf(name) for name in FIGURES}
    finally:
        if before_inputs != input_hashes():
            raise ValueError("A read-only source or generator changed during the run; coordinate with its owner and retry")
        if before_assets != _protected_binary_hashes(allowed):
            raise ValueError("A protected current or legacy figure asset changed during the run")
        if any(sha256(path) != digest for path, digest in before_receipts.items()):
            raise ValueError("An owner provenance receipt changed during verification; retry after owner completion")
    if regenerate or args.refresh_metadata:
        _write_metadata(env, mission, qa, provenance, _protected_binary_hashes(FIG1_OUTPUTS | MISSION_OUTPUTS))
    verify_metadata()
    print(f"PASS: five current figures; frozen B {ARCHIVE}; all source/generator/output hashes verified")
    print("  Generated scoped Figure 1/mission only." if regenerate else "  No figure scripts or outputs modified.")
    for name, info in qa.items():
        print(f"  {name}: {info['size_in']} in; minimum annotation {info['minimum_annotation_font_pt']} pt; "
              f"embedded fonts; raster images={info['raster_images_in_pdf']}")
    if args.refresh_metadata:
        print("  Refreshed source-manifest.json, figure-qa.json and plotted-data.json only.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
